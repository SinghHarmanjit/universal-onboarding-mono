const llmBaseUrl = process.env.LLM_BASE_URL || 'http://localhost:10030';
const llmModel = process.env.LLM_CONVERSATION_MODEL || 'gemma3';
const apiPort = process.env.PORT || '8000';
const ragApiUrl = `http://localhost:${apiPort}/v1/api/api/v1/query`;

console.log(`LLM Base URL: ${llmBaseUrl}`);
console.log(`LLM Model: ${llmModel}`);
console.log(`RAG API URL: ${ragApiUrl}`);

const llm = new ChatOpenAI({
  modelName: llmModel,
  maxTokens: 1024,
  temperature: 0,
  apiKey: process.env.GEMINI_API_KEY || 'not-needed-for-local',
  openAIApiKey: process.env.GEMINI_API_KEY || 'not-needed-for-local',
  configuration: {
    baseURL: llmBaseUrl.endsWith('/v1') ? llmBaseUrl : `${llmBaseUrl}/v1`,
  },
});

const evalPrompt = PromptTemplate.fromTemplate(`
You are an expert evaluator for a RAG system.
Given the question, the expected "golden" answer, and the actual generated answer, your task is to evaluate whether the generated answer is CORRECT and ALIGNED with the golden answer.
It is okay if the generated answer has more information, but it MUST be factually consistent with the golden answer and must directly answer the question.

Question: {question}
Golden Answer: {golden}
Generated Answer: {generated}

Please provide your evaluation in the following format:
SCORE: [PASS or FAIL]
REASON: [Short explanation for your score]
`);

async function queryRAG(question: string): Promise<string> {
  const response = await fetch(ragApiUrl, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ question }),
  });

  if (!response.body) throw new Error('No response body');

  const reader = response.body.getReader();
  const decoder = new TextDecoder();
  let result = '';

  while (true) {
    const { done, value } = await reader.read();
    if (done) break;
    const chunk = decoder.decode(value, { stream: true });
    // parse SSE lines
    const lines = chunk.split('\n');
    for (const line of lines) {
      if (line.startsWith('data: ')) {
        const dataStr = line.replace('data: ', '').trim();
        if (!dataStr) continue;
        try {
          const data = JSON.parse(dataStr);
          if (data.type === 'chunk' && data.content) {
            result += data.content;
          }
        } catch (e) {
          // ignore parsing error for malformed lines
        }
      }
    }
  }
  return result;
}

async function runEvaluation() {
  let passed = 0;
  console.log('Starting Evaluation...');
  for (const q of questions) {
    console.log(`\n--- Evaluating: "${q.question}" ---`);
    const generated = await queryRAG(q.question);
    console.log(`Generated Answer: \n${generated}`);

    const chain = evalPrompt.pipe(llm).pipe(new StringOutputParser());
    const evalResult = await chain.invoke({
      question: q.question,
      golden: q.golden,
      generated: generated,
    });

    console.log(`\nEvaluation:\n${evalResult}`);
    if (evalResult.includes('SCORE: PASS')) {
      passed++;
    }
  }

  console.log(`\n========================================`);
  console.log(`Final Score: ${passed}/${questions.length}`);
  console.log(`========================================\n`);
}

runEvaluation().catch(console.error);
